/**
 * A weak model that finished a file often writes the whole thing again with
 * small drift, and each copy is worse. The exact-signature check never fires
 * because the content differs, so successful whole-file writes are counted per
 * path. A test or shell run in between resets the count: rewriting after a
 * failing check is legitimate.
 */
export function trackWholeFileRewrites(
  counts: Map<string, number>,
  results: Array<{ tool: AgentEventToolName; ok: boolean; toolCallId: string; category?: ToolCategory }>,
  callsById: Map<string, { name: string; arguments: Record<string, unknown> }>,
  limits: { warnAt: number; stopAt: number } = { warnAt: 2, stopAt: 4 }
): { notice: string | null; exhaustedPath: string | null } {
  let notice: string | null = null;
  for (const result of results) {
    if (isVerificationToolResult(result)) {
      counts.clear();
      continue;
    }
    const call = callsById.get(result.toolCallId);
    const filePath = call?.name === "write_file" && typeof call.arguments.path === "string" ? call.arguments.path : null;
    if (!result.ok || !filePath) {
      continue;
    }
    const count = (counts.get(filePath) ?? 0) + 1;
    counts.set(filePath, count);
    if (count >= limits.stopAt) {
      return { notice: null, exhaustedPath: filePath };
    }
    if (count >= limits.warnAt) {
      notice =
        `You have now written ${filePath} in full ${count} times and it is saved on disk. ` +
        `Do not write the whole file again. Use edit for a targeted fix, run a check, or mark the todo item done and move to the next one.`;
    }
  }
  return { notice, exhaustedPath: null };
}

export function findRepeatedToolCall(toolCalls: Parameters<WorkspaceTools["execute"]>[0][], recentSignatures: string[]): Parameters<WorkspaceTools["execute"]>[0] | null {
  for (const toolCall of toolCalls) {
    const signature = toolCallSignature(toolCall);
    recentSignatures.push(signature);
    while (recentSignatures.length > 6) {
      recentSignatures.shift();
    }

    const threshold = toolCall.name === "update_todo" ? 2 : 3;
    if (recentSignatures.filter((item) => item === signature).length >= threshold) {
      return toolCall;
    }
  }

  return null;
}

function toolCallSignature(toolCall: Parameters<WorkspaceTools["execute"]>[0]): string {
  return `${toolCall.name}:${stableStringify(toolCall.arguments)}`;
}

function stableStringify(value: unknown): string {
  if (Array.isArray(value)) {
    return `[${value.map(stableStringify).join(",")}]`;
  }

  if (isRecord(value)) {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`)
      .join(",")}}`;
  }

  return JSON.stringify(value);
}

function normalizeToolCall(toolCall: Parameters<WorkspaceTools["execute"]>[0]): Parameters<WorkspaceTools["execute"]>[0] {
  if (toolCall.name === "search_text") {
    const query = typeof toolCall.arguments.query === "string" ? toolCall.arguments.query.trim() : "";
    if (!query) {
      return {
        name: "list_files",
        arguments: {
          path: "."
        }
      };
    }
  }

  return toolCall;
}


export function normalizeTodoItems(argumentsValue: Record<string, unknown>, existingItems: AgentTodoItem[] = []): AgentTodoItem[] {
  const rawItems = Array.isArray(argumentsValue.items) ? argumentsValue.items : Array.isArray(argumentsValue.todos) ? argumentsValue.todos : [];
  const existingById = new Map(existingItems.map((item) => [item.id, item]));
  const normalizedItems: AgentTodoItem[] = [];

  for (const rawItem of rawItems.slice(0, 12)) {
    if (!isRecord(rawItem)) {
      continue;
    }
    // "title" is what the nine-tool schema asks for; the rest are shapes
    // models reach for unprompted.
    const content =
      readTodoString(rawItem.content) ||
      readTodoString(rawItem.title) ||
      readTodoString(rawItem.text) ||
      readTodoString(rawItem.task) ||
      readTodoString(rawItem.description);
    if (!content) {
      continue;
    }
    const explicitId = readTodoString(rawItem.id);
    const id = sanitizeTodoId(explicitId || existingById.get(content)?.id || content);
    const status = normalizeTodoStatus(rawItem.status);
    normalizedItems.push({
      id,
      content: content.slice(0, 120),
      status
    });
  }

  return dedupeTodoItems(normalizedItems);
}

function summarizeTodos(items: AgentTodoItem[]): string {
  const completed = items.filter((item) => item.status === "completed").length;
  const active = items.find((item) => item.status === "in_progress");
  return active ? `${completed}/${items.length} done, working on ${active.content}` : `${completed}/${items.length} todos done`;
}


function dedupeTodoItems(items: AgentTodoItem[]): AgentTodoItem[] {
  const seen = new Set<string>();
  const deduped: AgentTodoItem[] = [];
  for (const item of items) {
    const uniqueId = seen.has(item.id) ? `${item.id}-${deduped.length + 1}` : item.id;
    seen.add(uniqueId);
    deduped.push({ ...item, id: uniqueId });
  }
  return deduped;
}

function normalizeTodoStatus(value: unknown): AgentTodoItem["status"] {
  const normalized = typeof value === "string" ? value.trim().toLowerCase().replace(/[- ]/g, "_") : "";
  if (normalized === "done" || normalized === "complete" || normalized === "completed" || normalized === "checked") {
    return "completed";
  }
  if (normalized === "active" || normalized === "doing" || normalized === "current" || normalized === "in_progress") {
    return "in_progress";
  }
  return "pending";
}

function sanitizeTodoId(value: string): string {
  const normalized = value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return normalized.slice(0, 40) || `todo-${Date.now().toString(36)}`;
}

function readTodoString(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

